const assert = require('node:assert/strict')
const path = require('node:path')
const { _electron } = require('playwright')

;(async () => {
    const app = await _electron.launch({ args: [path.join(__dirname, 'smoke-fixture.cjs')], cwd: path.resolve(__dirname, '..'), env: { ...process.env, TEST_CONSOLE_INPUT: '1' } })
    try {
        const page = await app.firstWindow()
        await app.evaluate(({ ipcMain }) => {
            const user = { signedIn: true, gamertag: 'Input test', gamerpic: '', gamerscore: '', level: 1 }
            ipcMain.removeAllListeners('app')
            ipcMain.on('app', (event, args) => {
                const data = args.action === 'getAuthState' ? { isAuthenticated: true, isAuthenticating: false, user }
                    : args.action === 'loadCachedUser' ? user : args.action === 'getOnlineFriends' ? [] : { autoStream: '' }
                event.sender.send('app', { id: args.id, action: args.action, data })
            })
        })
        await page.waitForLoadState('domcontentloaded')
        await page.goto('app://./settings/input.html')
        const panel = page.locator('[data-console-input]')
        await panel.waitFor()
        const selector = panel.getByLabel('Input mode', { exact: true })
        await selector.click()
        await page.waitForFunction(() => document.querySelector('[data-console-input] select').matches(':open'))
        await page.keyboard.press('Escape')
        await selector.selectOption('emulated')
        await panel.getByRole('button', { name: 'Capture input' }).click()
        await page.waitForFunction(() => document.pointerLockElement !== null)
        await page.keyboard.down('w'); await page.mouse.move(300, 200)
        await page.waitForTimeout(60)
        assert(await app.evaluate(() => global.inputPackets.some(p => p.type === 'pad' && p.state?.axes[1] === -1)), 'W must reach the headless pad')
        assert(await app.evaluate(() => global.inputPackets.some(p => p.type === 'pad' && p.state?.axes.slice(2).some(v => v !== 0))), 'Mouse movement must reach the aiming stick')
        await page.mouse.down({ button: 'left' }); await page.waitForTimeout(50)
        assert(await app.evaluate(() => global.inputPackets.some(p => p.type === 'pad' && p.state?.triggers[1] === 1)), 'Left click must reach RT')
        await page.keyboard.press('Escape'); await page.keyboard.up('w'); await page.mouse.up()
        await page.waitForFunction(() => !document.pointerLockElement)
        await app.evaluate(() => { global.inputPackets = [] })
        await page.waitForTimeout(80)
        assert(await app.evaluate(() => global.inputPackets.filter(p => p.type === 'pad').every(p => p.state.buttons === 0 && p.state.axes.every(v => v === 0) && p.state.triggers.every(v => v === 0))), 'Unlock must release every emulated control')
        await selector.selectOption('native')
        await panel.getByRole('button', { name: 'Capture input' }).click()
        await page.waitForFunction(() => document.pointerLockElement !== null)
        await page.keyboard.down('w'); await page.waitForTimeout(60)
        assert(await app.evaluate(() => global.inputPackets.some(p => p.type === 'native' && p.state.keys.some(k => k.code === 87 && k.pressed))), 'Native W must reach IPC')
        await page.mouse.wheel(0, 120); await page.waitForTimeout(50)
        assert(await app.evaluate(() => global.inputPackets.some(p => p.type === 'native' && p.state.mice?.some(m => m.wheelY !== 0))), 'Wheel must reach native IPC')
        await app.evaluate(async ({ BrowserWindow }) => {
            const other = new BrowserWindow({ width: 160, height: 120, show: true })
            global.inputFocusWindow = other
            await other.loadURL('about:blank'); other.focus()
        })
        await page.waitForFunction(() => document.pointerLockElement === null)
        assert(await app.evaluate(() => global.inputPackets.some(p => p.type === 'native' && p.state.reset)), 'Blur must send a native reset')
        await app.evaluate(({ BrowserWindow }) => { global.inputFocusWindow.close(); BrowserWindow.getAllWindows()[0].focus() })
        await page.keyboard.up('w')
        await panel.getByRole('button', { name: 'Capture input' }).click()
        await page.waitForFunction(() => document.pointerLockElement !== null)
        await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.send('console-input-reset'))
        await page.waitForFunction(() => !document.pointerLockElement)
        await selector.selectOption('controller')
        await page.waitForFunction(async () => (await window.Greenlight.send('settings', 'getSettings')).input_mode === 'controller')
        await page.reload(); await panel.waitFor()
        assert.equal(await panel.getByLabel('Input mode', { exact: true }).inputValue(), 'controller')
        const fs = require('node:fs'), folder = path.resolve(__dirname, '../../../.cache/screenshots')
        fs.mkdirSync(folder, { recursive: true })
        await page.screenshot({ path: path.join(folder, 'console-input.png') })
        console.log('Input smoke passed: real Electron pointer capture, WASD/trigger IPC, unlock release, native keys/wheel, blur release, three-mode switch and persistence. No console connected.')
    } finally { await app.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
